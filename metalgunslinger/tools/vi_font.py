TONE_LO = {  # 4-wide, 2 rows at rows 2-3 (hook: rows 1-3)
'\u0301':(2,['..#.','.#..']), '\u0300':(2,['.#..','..#.']),
'\u0303':(2,['.#.#','#.#.']), '\u0309':(1,['.##.','...#','..#.'])}
TONE_R  = {  # right-hand tone used together with circumflex/breve (cols 3-4)
'\u0301':['....#','...#.'], '\u0300':['...#.','....#'],
'\u0309':['...##','....#','...#.'], '\u0303':['..#.#','.#.#.']}

def _grid(): return [[0]*6 for _ in range(12)]
def _blit(g,rows,top,left=0):
    for y,r in enumerate(rows):
        for x,c in enumerate(r):
            if c=='#' and 0<=top+y<12 and 0<=left+x<6: g[top+y][left+x]=1

def glyph(ch):
    if ch in SYM:
        g=_grid(); _blit(g,SYM[ch],0); return g
    dec=unicodedata.normalize('NFD',ch)
    base,marks=dec[0],dec[1:]
    if base in 'Đđ' or ch in 'Đđ':
        base='D' if ch=='Đ' else 'd'
        g=_grid()
        if base=='D': _blit(g,UP['D'],3,1); _blit(g,['###'],6,0)
        else: _blit(g,LO['d'],3); _blit(g,['..###'],4)
        return g
    tone=[m for m in marks if m in TONE_LO]
    hat=[m for m in marks if m in ('\u0302','\u0306')]
    horn='\u031b' in marks; dotb='\u0323' in marks
    g=_grid()
    if base in UP:
        _blit(g,UP[base],3)
        w=max(len(r.rstrip('.')) for r in UP[base])
        if horn: g[2][4]=g[3][4]=1
        if hat:
            hr=['.#.','#.#'] if hat[0]=='\u0302' else ['#..#','.##.']
            if tone: _blit(g,hr if hat[0]=='\u0302' else ['#.#','.#.'],1); _blit(g,['...##','....#'] if tone[0]=='\u0309' else TONE_R[tone[0]][:2],0)
            else: _blit(g,['.##.','#..#'] if hat[0]=='\u0302' else ['#..#','.##.'],1)
        elif tone:
            t=TONE_LO[tone[0]][1]; _blit(g,t,0 if len(t)==3 else 1)
        if dotb: g[11][1]=1; g[11][2]=0
    elif base in LO:
        b=LO[base]
        if base=='i' and (tone or dotb): b=['','','','##.']+b[4:]   # dotless i
        if base=='i' and not tone: b=['','.#.','','##.']+b[4:] if not dotb else b
        _blit(g,b,3)
        if base=='i' and not tone and not dotb: pass
        if horn: g[4][4]=g[5][4]=1
        if hat:
            if tone:
                _blit(g,['.#.','#.#'] if hat[0]=='\u0302' else ['#.#','.#.'],2)
                _blit(g,TONE_R[tone[0]],0)
            else:
                _blit(g,['.##.','#..#'] if hat[0]=='\u0302' else ['#..#','.##.'],2)
        elif tone:
            top,t=TONE_LO[tone[0]]; off=-1 if base=='i' else 0
            _blit(g,[('.'+r)[1:] if off==0 else r[1:]+'.' for r in t],top)
        if dotb: g[11][1 if base!='y' else 4]=1
    else:
        raise KeyError('no glyph for %r'%ch)
    return g

